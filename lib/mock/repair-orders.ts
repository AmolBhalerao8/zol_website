export function getRepairOrder(ro: string): RepairOrder | undefined {
  return repairOrders.find((order) => order.ro.toLowerCase() === ro.toLowerCase());
}

export function getRepairOrdersForVehicle(vehicleId: string): RepairOrder[] {
  return repairOrders.filter((order) => order.vehicleId === vehicleId);
}

export function getRepairOrdersForCustomer(customerId: string): RepairOrder[] {
  return repairOrders.filter((order) => order.customerId === customerId);
}

export function orderSubtotal(order: RepairOrder): number {
  const labor = order.laborLines.reduce((sum, line) => sum + line.hours * line.rate, 0);
  const parts = order.partLines.reduce((sum, line) => sum + line.quantity * line.unitPrice, 0);
  return labor + parts;
}

